// Placeholder used while translating a .gitignore glob into a regex, so that a
// `**/` segment is not damaged by the later `*` substitution.
const GLOBSTAR = '@@GLOBSTAR@@';

const EXCLUDED_DIRS = new Set(['_archived', '_library', 'vendor', 'node_modules', 'build', 'dist', '.git', 'chatbot-logs', 'languages']);
const isExcludedDir = (name) => EXCLUDED_DIRS.has(name) || name.endsWith('-main') || name.startsWith('.');

const abs = (relative) => path.join(root, relative);
const posix = (p) => p.split(path.sep).join('/');
const exists = (relative) => fs.existsSync(abs(relative));
const readText = (relative) => fs.readFileSync(abs(relative), 'utf8').replace(/\r\n/g, '\n');
const byPath = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// --- unpublished-path detection -------------------------------------------
// Docs kept out of the open-source repository are declared in .gitignore. The
// public map/catalog must not expose their names, so the same patterns decide
// which entries land in the public file and which in the .local file.
function gitignoreRules() {
  if (!exists('.gitignore')) return [];
  return readText('.gitignore')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const negated = line.startsWith('!');
      let pattern = negated ? line.slice(1) : line;
      const dirOnly = pattern.endsWith('/');
      if (dirOnly) pattern = pattern.slice(0, -1);
      const anchored = pattern.startsWith('/');
      if (anchored) pattern = pattern.slice(1);
      const body = pattern
        .replace(/[.+^${}()|[\]\\]/g, '\\$&')
        .replace(/\*\*\//g, GLOBSTAR)
        .replace(/\*/g, '[^/]*')
        .replace(/\?/g, '[^/]')
        .split(GLOBSTAR).join('(?:.*/)?');
      const prefix = anchored ? '^' : '^(?:.*/)?';
      return { negated, dirOnly, regex: new RegExp(`${prefix}${body}(?:/.*)?$`) };
    });
}
const IGNORE_RULES = gitignoreRules();
function isUnpublished(relative) {
  let hidden = false;
  for (const rule of IGNORE_RULES) {
    if (!rule.regex.test(relative)) continue;
    hidden = !rule.negated;
  }
  return hidden;
}

function listFiles(relativeDir, { recursive = false, filter = () => true } = {}) {
  if (!exists(relativeDir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(abs(relativeDir), { withFileTypes: true })) {
    const rel = posix(path.join(relativeDir, entry.name));
    if (entry.isDirectory()) {
      if (recursive && !isExcludedDir(entry.name)) out.push(...listFiles(rel, { recursive, filter }));
    } else if (entry.isFile() && filter(entry.name, rel)) {
      out.push(rel);
    }
  }
  return out.sort(byPath);
}

function findDirsNamed(relativeDir, name, depth) {
  if (depth < 0 || !exists(relativeDir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(abs(relativeDir), { withFileTypes: true })) {
    if (!entry.isDirectory() || isExcludedDir(entry.name)) continue;
    const rel = posix(path.join(relativeDir, entry.name));
    if (entry.name === name) out.push(rel);
    else out.push(...findDirsNamed(rel, name, depth - 1));
  }
  return out.sort(byPath);
}

const clean = (line) => line
  .replace(/^>\s?/, '')
  .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
  .replace(/\*\*|__|`/g, '')
  .replace(/\s+/g, ' ')
  .trim();
const clip = (text, max = 140) => (text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text);
const cell = (text) => text.replace(/\|/g, '\\|');

// Title + optional status. Falls back to the first H2, then to the first prose
// line, when the H1 only repeats the filename (e.g. "# PHASE-0-RULE-CACHE.md").
function describeDoc(relative) {
  const lines = readText(relative).split('\n').slice(0, 60);
  const base = path.basename(relative, '.md').toLowerCase();
  let title = '';
  let status = '';
  let prose = '';
  let lead = '';
  let seen = 0;
  let inFence = false;
  let inFrontmatter = lines[0] === '---';
  for (const [index, raw] of lines.entries()) {
    const line = raw.trim();
    if (inFrontmatter) {
      if (index > 0 && line === '---') inFrontmatter = false;
      else if (!prose && line.startsWith('description:')) prose = clean(line.slice(12).replace(/^["']|["']$/g, ''));
      continue;
    }
    if (line.startsWith('```')) { inFence = !inFence; continue; }
    if (inFence || !line) continue;
    seen += 1;
    if (!lead && seen <= 3 && /^##\s+/.test(line)) { lead = clean(line.replace(/^##\s+/, '')); continue; }
    if (!title && /^#\s+/.test(line)) { title = clean(line.replace(/^#\s+/, '')); continue; }
    const statusMatch = line.match(/\*\*(Status|Tier)(?::\*\*|\*\*:)\s*(.+)$/i);
    if (!status && statusMatch) { status = clip(clean(statusMatch[2]), 60); continue; }
    if (!prose && !/^(#|---|\||<|!\[)/.test(line)) {
      const text = clean(line);
      if (text.length > 20 && !/^(Spec|Doc|Owner|Changelog|Source|Implementation|Version|Author|Date|Effective|Updated|Last updated|Tier|Status)\b/i.test(text)) prose = text;
    }
  }
  const titleIsFilename = !title || title.toLowerCase().replace(/\.md$/, '') === base;
  const summary = titleIsFilename ? (lead || prose || title || path.basename(relative)) : title;
  return { summary: clip(summary), status };
}

function describeScript(relative) {
  const lines = readText(relative).split('\n').slice(0, 20);
  // PowerShell comment-based help: take the line after .SYNOPSIS.
  if (lines[0] && lines[0].trim().startsWith('<#')) {
    const synopsis = lines.findIndex((line) => line.trim().toUpperCase() === '.SYNOPSIS');
    const text = synopsis === -1 ? '' : clean(lines.slice(synopsis + 1).find((line) => line.trim()) || '');
    if (text) return clip(text, 130);
  }
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#!') || /^<\?php/.test(line) || /^(declare|import|use|namespace|const|require|param|set -)/.test(line)) continue;
    const comment = line.match(/^(?:\/\/+|#+|\/\*+|\*+)\s*(.*?)\s*(?:\*\/)?$/);
    if (!comment) continue;
    const text = clean(comment[1]);
    if (text.length > 8 && !text.startsWith('@') && /[A-Za-z]/.test(text)) return clip(text, 130);
  }
  return '(no header — read the file before running)';
}

function commandFor(relative) {
  if (relative.endsWith('.mjs') || relative.endsWith('.js')) return `node ${relative}`;
  if (relative.endsWith('.php') || relative === 'bin/twin') return `php ${relative}`;
  if (relative.endsWith('.ps1')) return `pwsh ${relative}`;
  if (relative.endsWith('.sh')) return `bash ${relative}`;
  return relative;
}

function ciCommands() {
  const file = '.github/workflows/ci.yml';
  if (!exists(file)) return [];
  const commands = [];
  const lines = readText(file).split('\n');
  const keep = (text) => {
    const cmd = text.trim().replace(/;\s*then$/, '');
    const balancedQuotes = cmd.split("'").length % 2 === 1;
    if (/^(node|php|npx|composer|vendor\/bin|"\$PHP|\$PHP)\b/.test(cmd) && !/<<\s*'?\w+'?/.test(cmd) && balancedQuotes && !commands.includes(cmd)) commands.push(cmd);
  };
  for (let i = 0; i < lines.length; i += 1) {
    const match = lines[i].match(/^(\s*)(?:-\s+)?run:\s*(.*)$/);
    if (!match) continue;
    if (match[2] && match[2] !== '|' && match[2] !== '>') { keep(match[2]); continue; }
    const indent = match[1].length;
    let inHeredoc = null;
    for (i += 1; i < lines.length; i += 1) {
      const line = lines[i];
      if (line.trim() && line.search(/\S/) <= indent) { i -= 1; break; }
      if (inHeredoc) { if (line.trim() === inHeredoc) inHeredoc = null; continue; }
      const heredoc = line.match(/<<\s*'?(\w+)'?/);
      if (heredoc) { inHeredoc = heredoc[1]; continue; }
      keep(line.replace(/^\s*(if|then)\s+/, ''));
    }
  }
  return commands;
}

