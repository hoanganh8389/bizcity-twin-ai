// 5. Privacy gate — no deployment identity in any public artifact
// ---------------------------------------------------------------------------
const publicArtifacts = [mainSource, ...scopedPublic, 'AGENTS.md', catalogFile, 'CLAUDE.md'].filter((rel) => outputs.has(rel) || exists(rel));
const leaks = [];
for (const rel of publicArtifacts) {
  const text = outputs.has(rel) ? outputs.get(rel) : readText(rel);
  text.split('\n').forEach((line, index) => {
    for (const marker of PRIVATE_MARKERS) {
      if (marker.test(line)) leaks.push(`${rel}:${index + 1} matches ${marker}`);
    }
  });
}
if (leaks.length) {
  console.error('[R-AGENT-PARITY] FAIL: deployment identity found in public artifacts:');
  for (const leak of leaks.slice(0, 20)) console.error(`  ${leak}`);
  console.error('Move host names, operator paths and domains into the .local files.');
  process.exit(2);
}

// Relative links in committed docs must resolve for someone who only has the
// public repository: a link into an unpublished path is dead for contributors.
const linkedDocs = ['README.md', 'CONTRIBUTING.md', 'SECURITY.md', mainSource, ...scopedPublic].filter((rel) => outputs.has(rel) || exists(rel));
const deadLinks = [];
for (const rel of linkedDocs) {
  const text = outputs.has(rel) ? outputs.get(rel) : readText(rel);
  const base = path.posix.dirname(rel);
  text.split('\n').forEach((line, index) => {
    for (const match of line.matchAll(/\]\(([^)\s#]+)(?:#[^)\s]*)?\)/g)) {
      const target = match[1];
      if (/^(https?:|mailto:|#)/.test(target)) continue;
      const resolved = posix(path.posix.normalize(path.posix.join(base, target))).replace(/^\.\//, '');
      if (resolved.startsWith('..')) continue;
      if (!exists(resolved) && !outputs.has(resolved)) deadLinks.push(`${rel}:${index + 1} → ${resolved} (missing)`);
      else if (isUnpublished(resolved)) deadLinks.push(`${rel}:${index + 1} → ${resolved} (not published)`);
    }
  });
}
if (deadLinks.length) {
  console.error('[R-AGENT-PARITY] FAIL: committed docs link to files the public repository does not ship:');
  for (const link of deadLinks.slice(0, 40)) console.error(`  ${link}`);
  console.error('Link to a published document, or describe the rule inline instead of linking.');
  process.exit(3);
}

// `.local.` naming contract: a private instruction/index file is recognisable by
// its name alone, and a `.local.` name always means git-ignored.
const instructionScope = [
  ...listFiles('.github', { recursive: true, filter: (n) => /\.(md|json|ya?ml)$/.test(n) }),
  ...listFiles('.claude', { recursive: true, filter: (n) => /\.(md|json)$/.test(n) }),
  ...listFiles('.', { filter: (n) => /\.md$/.test(n) }),
  ...listFiles('docs', { filter: (n) => /^AGENT-/.test(n) }),
];
const isLocalName = (rel) => path.basename(rel).includes('.local.');
const namingErrors = [];
for (const rel of [...new Set(instructionScope)].sort(byPath)) {
  const local = isLocalName(rel);
  const ignored = isUnpublished(rel);
  if (local && !ignored) namingErrors.push(`${rel} is named .local. but is NOT git-ignored — add it to .gitignore`);
  if (!local && ignored) namingErrors.push(`${rel} is git-ignored but has no .local. in its name — rename it to *.local.*`);
}
// A `.local.` name anywhere in the tree must be git-ignored too.
for (const rel of ['docs', 'core', 'modules', 'plugins', 'bin', 'tests'].flatMap((dir) => listFiles(dir, { recursive: true, filter: (n) => n.includes('.local.') }))) {
  if (!isUnpublished(rel)) namingErrors.push(`${rel} is named .local. but is NOT git-ignored — add it to .gitignore`);
}
if (namingErrors.length) {
  console.error('[R-AGENT-PARITY] FAIL: `.local.` naming contract violated:');
  for (const problem of [...new Set(namingErrors)].slice(0, 40)) console.error(`  ${problem}`);
  console.error('Public file = plain name; private twin = same name with .local. + .gitignore entry.');
  process.exit(4);
}

