function withMarkerBlock(relative, imports, missingHint) {
  const current = readText(relative);
  const block = [claudeStart, '', ...imports.flatMap((rel) => [`@${rel}`, '']), claudeEnd].join('\n');
  const start = current.indexOf(claudeStart);
  const end = current.indexOf(claudeEnd);
  if (start === -1 || end === -1) {
    console.error(`[R-AGENT-PARITY] FAIL: ${relative} is missing the markers:\n${claudeStart}\n${claudeEnd}\n${missingHint}`);
    process.exit(1);
  }
  return current.slice(0, start) + block + current.slice(end + claudeEnd.length);
}

