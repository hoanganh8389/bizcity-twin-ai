function buildCatalog(visible) {
  const head = visible
    ? [
      '<!-- GENERATED FILE — DO NOT EDIT. Regenerate: node bin/sync-agent-instructions.mjs -->',
      '',
      '# Agent Doc Catalog — published documentation',
      '',
      '> On-demand catalog for AI agents: grep this file for a topic, then open the doc.',
      '> Always-loaded summary: `.github/instructions/agent-environment.instructions.md`.',
    ]
    : [
      '<!-- GENERATED FILE — DO NOT EDIT. Regenerate: node bin/sync-agent-instructions.mjs -->',
      '',
      '# Agent Doc Catalog — internal documentation (not published)',
      '',
      '> Documents excluded from the public repository by `.gitignore`.',
      '> Never quote their contents into a public file, issue or pull request.',
    ];
  const body = [];
  let total = 0;
  for (const dir of ['docs', ...docDirs]) {
    const files = listFiles(dir, { recursive: true, filter: (n, rel) => isMd(n) && !generatedDocs.has(rel) })
      .filter((rel) => isUnpublished(rel) === !visible);
    if (!files.length) continue;
    body.push(`## \`${dir}\` (${files.length})`, '', '| File | Summary | Status |', '|---|---|---|');
    for (const rel of files) {
      const { summary, status } = describeDoc(rel);
      body.push(`| \`${rel}\` | ${cell(summary)} | ${cell(status)} |`);
    }
    body.push('');
    total += files.length;
  }
  return `${[...head, `> Total: ${total} files.`, '', ...body].join('\n')}\n`;
}

